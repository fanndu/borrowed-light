/** Hand-authored campaign. Orientations below describe one intended solution;
 * `turns` identifies the mirrors deliberately displaced in the starting board.
 * Pars are certified by exhaustive enumeration in tests/levels.test.mjs. */
const S = (x, y, dir = 0, color = "gold") => ({
  type: "source",
  x,
  y,
  dir,
  color,
});
const M = (x, y, state = 0) => ({ type: "mirror", x, y, state });
const P = (x, y, state = 0) => ({ type: "splitter", x, y, state });
const F = (x, y, color) => ({ type: "filter", x, y, color });
const T = (x, y, color = "gold") => ({ type: "target", x, y, color });
const Z = (x, y) => ({ type: "sleeper", x, y });
const W = (x, y) => ({ type: "wall", x, y });
function L(id, title, brief, cells, turns, options = {}) {
  const flipped = new Set(turns.split(" ").filter(Boolean));
  return {
    id,
    title,
    brief,
    chapter: Math.floor((id - 1) / 6),
    cols: 7,
    rows: 7,
    par: flipped.size,
    ...options,
    cells: cells.map((cell) =>
      flipped.has(`${cell.x},${cell.y}`)
        ? { ...cell, state: 1 - cell.state }
        : cell,
    ),
  };
}
